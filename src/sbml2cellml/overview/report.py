"""The pages across the checks, `docs/benchmarks.md` and `docs/models.md`.

`render_benchmarks` compares the wall time of the two simulators over the
models of every check, `render_models` which models of every check the
converters handle. Both read the committed results of the checks
(`sbml2cellml.overview.checks`), neither of them runs a simulation.
"""

from pathlib import Path, PurePosixPath
from statistics import median

from sbml2cellml.overview.checks import ROLES, Run, works
from sbml2cellml.overview.figure import (
    PHASES,
    write_median_figures,
    write_scatter_figures,
)
from sbml2cellml.testsuite.figure import dark_path, duration_text, timing_pairs
from sbml2cellml.testsuite.report import cell, solver_text

#: command which writes the two pages
COMMAND = "sbml2cellml-overview"
#: the scatter of a phase, relative to the benchmark page; the integration
#: is `images/benchmarks.svg`, the figure `README.md` shows as well
FIGURES = {
    "setup": "images/benchmarks_setup.svg",
    "integration": "images/benchmarks.svg",
    "total": "images/benchmarks_total.svg",
}
#: the median wall times of every phase, relative to the benchmark page
MEDIANS_FIGURE = "images/benchmarks_medians.svg"
#: heading of the section of a phase
HEADINGS = {"setup": "Setup", "integration": "Integration", "total": "Total"}
#: what a phase measures, the first sentence of its section
PHASE_TEXT = {
    "setup": (
        "The setup is everything a simulator does with a model before it "
        "integrates: reading and converting the file, generating and "
        "compiling the code of the model and building the instance. It "
        "takes longer than the integration for the median model of every "
        "check."
    ),
    "integration": (
        "The integration is the run of the solver over the output grid, "
        "the same grid and the same tolerances for both simulators."
    ),
    "total": (
        "The setup and the integration of a model together, what a "
        "simulator costs for a model which is simulated once; a model "
        "simulated again in the same process needs no setup, since both "
        "simulators cache what they compiled."
    ),
}
#: number of the slowest models of a check in the benchmark page
SLOWEST = 5


def _header(title: str) -> list[str]:
    """First lines of a generated page: the marker and the heading."""
    return [f"<!-- generated by {COMMAND}, do not edit -->", f"# {title}", ""]


def _figure(path: str, alt: str) -> list[str]:
    """The figure for light and the one for dark backgrounds.

    Args:
        path: path of the figure for light backgrounds, relative to the page.
        alt: alternative text of the figure.

    Returns:
        The markdown lines, the variant matching the color scheme of the
        site.
    """
    dark = dark_path(PurePosixPath(path))
    return [f"![{alt}]({path}#only-light)", f"![{alt}]({dark}#only-dark)", ""]


def _percent(count: int, total: int) -> str:
    """A count as a percentage of a total, e.g. `99.7%`."""
    return f"{100 * count / (total or 1):.1f}%"


def _checks_lines(runs: list[Run]) -> list[str]:
    """One bullet per check: its page, how many models it runs and their source."""
    lines = []
    for run in runs:
        check = run.check
        lines.append(
            f"- [{check.title}]({check.page}): {len(run.result.cases)} "
            f"{check.unit}, {check.source}"
        )
    return [*lines, ""]


def _phase_section(runs: list[Run], phase: str, figure: str) -> list[str]:
    """The section of one phase: its figure, what it measures and its table.

    Args:
        runs: the runs of the checks.
        phase: the phase of a simulation, a key of
            `sbml2cellml.overview.figure.PHASES`.
        figure: path of the scatter of the phase, relative to the page.

    Returns:
        The markdown lines, one row per check with a timed model.
    """
    seconds, _ = PHASES[phase]
    heading = HEADINGS[phase]
    lines = [
        f"## {heading}",
        "",
        *_figure(figure, f"{heading} time of libopencor against sbmlsim-core"),
        PHASE_TEXT[phase],
        "",
        "| check | models | sbmlsim-core | libopencor | ratio | "
        "libopencor faster | sbmlsim-core sum | libopencor sum |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for run in runs:
        pairs = seconds(run.result)
        if not pairs:
            continue
        sbmlsim = [pair[0] for pair in pairs.values()]
        libopencor = [pair[1] for pair in pairs.values()]
        ratios = [pair[1] / pair[0] for pair in pairs.values()]
        faster = sum(1 for pair in pairs.values() if pair[1] <= pair[0])
        lines.append(
            f"| [{run.check.title}]({run.check.page}) | {len(pairs)} | "
            f"{duration_text(median(sbmlsim))} | "
            f"{duration_text(median(libopencor))} | {median(ratios):.2f} | "
            f"{faster} of {len(pairs)} | {duration_text(sum(sbmlsim))} | "
            f"{duration_text(sum(libopencor))} |"
        )
    return [*lines, ""]


def render_benchmarks(
    runs: list[Run],
    figures: dict[str, str] | None = None,
    medians: str = MEDIANS_FIGURE,
) -> str:
    """Render the benchmark page.

    Args:
        runs: the runs of the checks.
        figures: path of the scatter of every phase, relative to the page,
            `FIGURES` when `None`; written by `write_benchmarks`.
        medians: path of the median wall times, relative to the page.

    Returns:
        The markdown page.
    """
    scatters = figures or FIGURES
    lines = [
        *_header("Benchmarks"),
        "Wall time of the two simulators of the project over the models of "
        "every check: [libopencor](https://opencor.ws/libopencor/) "
        "simulates the CellML model and "
        "[sbmlsim-core](https://matthiaskoenig.github.io/sbmlsim-core/) the "
        "SBML model of the same system, one of the two converted from the "
        "other, over the same output grid and with the same solver "
        "settings. The pass rates of the conversions are on the "
        "[Models](models.md) page.",
        "",
        *_checks_lines(runs),
        "Only the models whose converted model reproduces the simulation of "
        "the source model are compared: the two simulators integrate the "
        "same dynamics there, which a model with a conversion gap does not. "
        f"{solver_text()}",
        "",
        "Every wall time is measured inside the simulator wrapper in the "
        "worker process of the harness, so it holds no overhead of the "
        "harness. Both simulators run a model once before the run of the "
        "result, so that the generation of the code of a model, which "
        "libopencor does when it runs a model the first time, is part of "
        "its setup.",
        "",
        "The numbers are the committed runs of the checks on one machine: "
        "they compare the two simulators with each other over the same "
        "models, they are no absolute performance figures. In every table "
        "the ratio is the median of the time of libopencor divided by the "
        "time of sbmlsim-core per model, so a ratio below one means "
        "libopencor is faster for the median model, and the sum is the "
        "wall time of all models of the check.",
        "",
        "## Summary",
        "",
        *_figure(medians, "Median setup, integration and total time per check"),
    ]
    for phase in PHASES:
        lines += _phase_section(runs, phase, scatters[phase])

    lines += [
        "## Slowest models",
        "",
        f"The {SLOWEST} models of every check with the longest "
        "integration, by the longer of the two times.",
        "",
    ]
    for run in runs:
        pairs = timing_pairs(run.result)
        if not pairs:
            continue
        named = any(run.result.cases[cid].name for cid in pairs)
        slowest = sorted(pairs.items(), key=lambda item: -max(item[1]))[:SLOWEST]
        name_header = "name | " if named else ""
        name_separator = "--- | " if named else ""
        lines += [
            f"### {run.check.title}",
            "",
            f"| model | {name_header}sbmlsim-core | libopencor | ratio |",
            f"| --- | {name_separator}--- | --- | --- |",
        ]
        for cid, (sbmlsim, libopencor) in slowest:
            name = f"{cell(run.result.cases[cid].name)} | " if named else ""
            lines.append(
                f"| {run.check.link(cid)} | {name}{duration_text(sbmlsim)} | "
                f"{duration_text(libopencor)} | {libopencor / sbmlsim:.2f} |"
            )
        lines.append("")
    return "\n".join(lines)


def render_models(runs: list[Run]) -> str:
    """Render the page of the models of the checks.

    Args:
        runs: the runs of the checks.

    Returns:
        The markdown page: the pass rate of every stage per check, every
        model of a check of published models with the status of its stages,
        and the models which do not run at all.
    """
    total = sum(len(run.result.cases) for run in runs)
    lines = [
        *_header("Models"),
        f"Which models the converters handle: {total} models of "
        f"{len(runs)} checks, from a case written for one feature of SBML "
        "to a published model of many components. Every "
        "model is simulated, converted to the other language, simulated "
        "again and compared, converted back and simulated once more; a "
        "model **works** when every one of these stages passes. The wall "
        "times of the simulations are on the [Benchmarks](benchmarks.md) "
        "page.",
        "",
        *_checks_lines(runs),
        "A check whose source is the SBML model and one whose source is the "
        "CellML model name the stages differently, the role of a stage is "
        "the same:",
        "",
        "| check | " + " | ".join(ROLES) + " |",
        "| --- | " + " | ".join("---" for _ in ROLES) + " |",
    ]
    for run in runs:
        stages = " | ".join(f"`{stage}`" for stage in run.result.stages)
        lines.append(f"| [{run.check.title}]({run.check.page}) | {stages} |")

    lines += [
        "",
        "## Overview",
        "",
        "The share of the models which pass a stage, the models which pass "
        "every stage and the models which do not run at all, whose reason "
        "is in the report of the check.",
        "",
        "| check | models | " + " | ".join(ROLES) + " | works | skipped |",
        "| --- | --- | " + " | ".join("---" for _ in ROLES) + " | --- | --- |",
    ]
    for run in runs:
        result = run.result
        cases = len(result.cases)
        rates = " | ".join(
            _percent(result.counts(stage)["pass"], cases) for stage in result.stages
        )
        working = sum(1 for cid in result.cases if works(run, cid))
        lines.append(
            f"| [{run.check.title}]({run.check.page}) | {cases} | {rates} | "
            f"{working} ({_percent(working, cases)}) | {len(result.skipped)} |"
        )

    for run in runs:
        if run.check.url is None:
            continue
        result = run.result
        working = sum(1 for cid in result.cases if works(run, cid))
        lines += [
            "",
            f"## {run.check.title}",
            "",
            f"{working} of the {len(result.cases)} models work, the errors "
            f"of the others are in the [report]({run.check.page}).",
            "",
            "| model | name | " + " | ".join(result.stages) + " | works |",
            "| --- | --- | " + " | ".join("---" for _ in result.stages) + " | --- |",
        ]
        for cid, case in sorted(result.cases.items()):
            statuses = " | ".join(case.stages[stage].status for stage in result.stages)
            lines.append(
                f"| {run.check.link(cid)} | {cell(case.name)} | {statuses} | "
                f"{'yes' if works(run, cid) else 'no'} |"
            )

    skipped = [
        (run, model_id, reason)
        for run in runs
        if run.check.url is not None
        for model_id, reason in sorted(run.result.skipped.items())
    ]
    if skipped:
        lines += [
            "",
            "## Models which do not run",
            "",
            "A model which is not simulated at all, because its file is "
            "missing, cannot be read or cannot be analysed. The cases a "
            "check skips for a missing feature are in its own report.",
            "",
            "| check | model | reason |",
            "| --- | --- | --- |",
        ]
        for run, model_id, reason in skipped:
            lines.append(
                f"| {run.check.title} | {run.check.link(model_id)} | {cell(reason)} |"
            )
    return "\n".join([*lines, ""])


def write_benchmarks(
    runs: list[Run],
    path: Path,
    figures: dict[str, str] | None = None,
    medians: str = MEDIANS_FIGURE,
) -> None:
    """Write the benchmark page, the scatter of every phase and the medians.

    Args:
        runs: the runs of the checks.
        path: markdown file, overwritten.
        figures: path of the scatter of every phase, relative to the page,
            `FIGURES` when `None`.
        medians: path of the median wall times, relative to the page.
    """
    path = Path(path)
    scatters = figures or FIGURES
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        render_benchmarks(runs, figures=scatters, medians=medians), encoding="utf-8"
    )
    for phase, figure in scatters.items():
        write_scatter_figures(runs, path.parent / figure, phase=phase)
    write_median_figures(runs, path.parent / medians)


def write_models(runs: list[Run], path: Path) -> None:
    """Write the page of the models of the checks.

    Args:
        runs: the runs of the checks.
        path: markdown file, overwritten.
    """
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_models(runs), encoding="utf-8")
