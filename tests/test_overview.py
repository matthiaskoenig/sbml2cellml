def test_committed_pages_are_the_pages_of_the_committed_results() -> None:
    """The two pages are rendered from the results files, nothing else."""
    loaded = load_runs({check.name: REPO / check.results for check in CHECKS})
    assert [run.check.name for run in loaded] == [check.name for check in CHECKS]
    for page, rendered in (
        ("benchmarks.md", render_benchmarks(loaded)),
        ("models.md", render_models(loaded)),
    ):
        committed = (REPO / "docs" / page).read_text(encoding="utf-8")
        assert committed == rendered, f"docs/{page} is stale, run sbml2cellml-overview"
