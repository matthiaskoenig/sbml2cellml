def test_render_benchmarks_without_a_timed_model() -> None:
    result = sbml_first()
    for case in result.cases.values():
        case.stages["libopencor"] = StageResult("fail", "no simulation")
    text = render_benchmarks([Run(check=runs()[0].check, result=result)])
    assert "## Integration" in text
    assert "| [BioModels](biomodels.md) |" not in text


def test_write_benchmarks_writes_both_figures(tmp_path: Path) -> None:
    page = tmp_path / "benchmarks.md"
    write_benchmarks(runs(), page)
    assert page.is_file()
    for figure in (*FIGURES.values(), MEDIANS_FIGURE):
        light = tmp_path / figure
        assert light.is_file()
        assert dark_path(light).is_file()
        assert light.read_text(encoding="utf-8") != dark_path(light).read_text(
            encoding="utf-8"
        )


def test_write_models(tmp_path: Path) -> None:
    page = tmp_path / "pages" / "models.md"
    write_models(runs(), page)
    assert page.read_text(encoding="utf-8") == render_models(runs())


def test_cli_writes_both_pages(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    biomodels = tmp_path / "biomodels.json"
    physiome = tmp_path / "physiome.json"
    sbml_first().to_json(biomodels)
    cellml_first().to_json(physiome)
    benchmarks = tmp_path / "docs" / "benchmarks.md"
    models = tmp_path / "docs" / "models.md"
    code = main(
        [
            "--testsuite",
            str(tmp_path / "missing.json"),
            "--biomodels",
            str(biomodels),
            "--physiome",
            str(physiome),
            "--benchmarks",
            str(benchmarks),
            "--models",
            str(models),
            "-v",
        ]
    )
    assert code == 0
    assert benchmarks.is_file()
    assert models.is_file()
    for figure in (*FIGURES.values(), MEDIANS_FIGURE):
        assert (tmp_path / "docs" / figure).is_file()
    assert "2 checks (biomodels, physiome)" in capsys.readouterr().out


