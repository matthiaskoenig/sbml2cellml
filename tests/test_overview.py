def _case(
    case_id: str,
    stages: tuple[str, ...],
    failing: str | None = None,
    seconds: tuple[float, float] = (0.02, 0.01),
    name: str = "",
) -> CaseResult:
    """A case whose `sbmlsim` and `libopencor` stage are timed."""
    results = {stage: StageResult("pass") for stage in stages}
    if failing is not None:
        results[failing] = StageResult("fail", "S1 exceeds the tolerance by 0.5", 0.5)
    for stage, value, setup in (
        ("sbmlsim", seconds[0], 0.2),
        ("libopencor", seconds[1], 0.4),
    ):
        results[stage] = StageResult(
            results[stage].status,
            results[stage].message,
            results[stage].max_excess,
            seconds=value,
            setup_seconds=setup,
        )
    return CaseResult(case_id, [], ["Compartment"], results, name=name)


def sbml_first() -> SuiteResult:
    """A run whose source is the SBML model, one case of two failing."""
    return SuiteResult(
        "biomodels",
        "0.1.0",
        {
            "BIOMD0000000001": _case(
                "BIOMD0000000001", STAGES, name="Edelstein1996", seconds=(0.02, 0.01)
            ),
            "BIOMD0000000002": _case(
                "BIOMD0000000002",
                STAGES,
                failing="libopencor",
                name="Goldbeter1991",
                seconds=(0.5, 0.25),
            ),
        },
        {"BIOMD0000000003": "no variables"},
        stages=STAGES,
    )


def cellml_first() -> SuiteResult:
    """A run whose source is the CellML model."""
    return SuiteResult(
        "physiome",
        "0.1.0",
        {"105": _case("105", CELLML_STAGES, name="Jejunal smooth muscle")},
        {"10": "model cannot be analysed"},
        stages=CELLML_STAGES,
    )


def runs() -> list[Run]:
    """A run of the BioModels and one of the Physiome check."""
    checks = {check.name: check for check in CHECKS}
    return [
        Run(check=checks["biomodels"], result=sbml_first()),
        Run(check=checks["physiome"], result=cellml_first()),
    ]


def test_link_of_a_check_without_a_url() -> None:
    check = Check(
        name="testsuite",
        title="SBML test suite",
        short="SBML test suite",
        page="testsuite.md",
        results=Path("testsuite") / "results.json",
        command="sbml2cellml-testsuite",
        unit="cases",
        source="the semantic cases",
    )
    assert check.link("00001") == "00001"


def test_link_of_a_model() -> None:
    check = {check.name: check for check in CHECKS}["physiome"]
    assert check.link("105") == "[105](https://models.physiomeproject.org/e/105)"


def test_every_check_links_its_report_page() -> None:
    for check in CHECKS:
        assert (REPO / "docs" / check.page).is_file()


def test_load_runs_skips_a_missing_results_file(
    tmp_path: Path, caplog: pytest.LogCaptureFixture
) -> None:
    path = tmp_path / "results.json"
    sbml_first().to_json(path)
    with caplog.at_level(logging.WARNING):
        loaded = load_runs(
            {
                "testsuite": tmp_path / "missing.json",
                "biomodels": path,
                "physiome": tmp_path / "gone.json",
            }
        )
    assert [run.check.name for run in loaded] == ["biomodels"]
    assert len(loaded[0].result.cases) == 2
    assert "no results of the testsuite check" in caplog.text


def test_works_requires_every_stage() -> None:
    run = runs()[0]
    assert works(run, "BIOMD0000000001")
    assert not works(run, "BIOMD0000000002")


def test_render_models_lists_every_model() -> None:
    text = render_models(runs())
    assert text.startswith("<!-- generated by sbml2cellml-overview, do not edit -->")
    assert (
        "| [BIOMD0000000001](https://www.ebi.ac.uk/biomodels/BIOMD0000000001) | "
        "Edelstein1996 | pass | pass | pass | pass | pass | yes |" in text
    )
    assert (
        "| [BIOMD0000000002](https://www.ebi.ac.uk/biomodels/BIOMD0000000002) | "
        "Goldbeter1991 | pass | pass | fail | pass | pass | no |" in text
    )
    assert "| [105](https://models.physiomeproject.org/e/105) |" in text


def test_render_models_counts_the_models_which_work() -> None:
    text = render_models(runs())
    # the stages of the two checks in their own order, as the role table has them
    assert "| [BioModels](biomodels.md) | `sbmlsim` | `sbml2cellml` |" in text
